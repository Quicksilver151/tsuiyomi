#!/usr/bin/env python3
"""Regenerate the Rust dependency license inventory.

The release archives bundle compiled Rust code, so the third-party notices should list
every crate that can end up in a binary. `cargo metadata` is the source of truth; run
this after changing `Cargo.lock` and commit the result.

Usage:
    python3 scripts/dependency-notices.py          # rewrite the inventory
    python3 scripts/dependency-notices.py --check  # fail if it is stale
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "licenses" / "RUST-DEPENDENCIES.txt"


def render() -> str:
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1"],
            cwd=ROOT,
        )
    )
    packages = {
        (package["name"], package["version"], package.get("license") or "see package source")
        for package in metadata["packages"]
        if package.get("source") is not None
    }

    lines = [
        "Rust dependency license inventory",
        "",
        "Generated by scripts/dependency-notices.py from Cargo.lock. Do not edit by hand.",
        "Each crate's full license text and copyright notice live in its package source.",
        "",
    ]
    for name, version, license_name in sorted(packages):
        lines.append(f"{name} {version} — {license_name}")
    return "\n".join(lines) + "\n"


def main() -> int:
    rendered = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current != rendered:
            print(f"{OUTPUT} is stale; run scripts/dependency-notices.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    print(f"Wrote {OUTPUT} ({rendered.count(chr(10)) - 4} crates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
